export const CAPTION =
  "This interactive dashboard serves both as a teaching tool to introduce matrices and linear algebra, as well as a demonstration for students of coding with AI agents. The code for this dashboard was generated by GPT-6-Astra using OpenAI Codex CLI, with human-in-the-loop interventions at every substantive step in the design and development process. This is an example of a simple, single-session task completed without any AGENTS.md file to tailor model behavior. The prompts used for the project are available in the repository's documentation.";
const GREEN = "#177e70",
  DARK = "#273b4a";
type Dispatch = (a: Action) => void;
function Dimensions({
  m,
  n,
  onChange,
}: {
  m: number;
  n: number;
  onChange: (m: number, n: number) => void;
}) {
  return (
    <div className="dimensions">
      <label>
        Rows · output
        <select
          aria-label="Rows: output dimension"
          value={m}
          onChange={(e) => onChange(Number(e.target.value), n)}
        >
          {[1, 2, 3].map((d) => (
            <option key={d}>{d}</option>
          ))}
        </select>
      </label>
      <span>×</span>
      <label>
        Columns · input
        <select
          aria-label="Columns: input dimension"
          value={n}
          onChange={(e) => onChange(m, Number(e.target.value))}
        >
          {[1, 2, 3].map((d) => (
            <option key={d}>{d}</option>
          ))}
        </select>
      </label>
    </div>
  );
}
function Stats({ matrix, symbol = "A" }: { matrix: Matrix; symbol?: string }) {
  const r = rank(matrix),
    d = determinant(matrix);
  return (
    <div className="stats" aria-live="polite">
      <div>
        <span>Rank {symbol}</span>
        <strong data-testid="rank">{r}</strong>
        <small>
          {r} independent column direction{r === 1 ? "" : "s"}
        </small>
      </div>
      <div>
        <span>Determinant {symbol}</span>
        <strong data-testid="determinant">
          {d ? d.toString() : "Not defined"}
        </strong>
        <small>
          {d === null
            ? "Matrix is not square"
            : d.zero
              ? "Collapse: zero volume in this dimension"
              : `${d.n < 0n ? "Reverses" : "Preserves"} orientation · ${d.n < 0n ? d.neg() : d}× ${["", "length", "area", "volume"][matrix.length]}`}
        </small>
      </div>
    </div>
  );
}
function columnArrows(
  a: Matrix,
  name: string,
  onChange?: (j: number, v: number[]) => void,
): Arrow[] {
  return columns(a).map((value, j) => ({
    id: `column-${j}`,
    label: `${name}${j + 1}`,
    value,
    color: COLORS[j],
    onChange: onChange ? (v) => onChange(j, v) : undefined,
  }));
}
function Combination({
  a,
  x,
  symbol = "A",
  input = "x",
  col = "a",
}: {
  a: Matrix;
  x: Vector;
  symbol?: string;
  input?: string;
  col?: string;
}) {
  const y = multiplyVector(a, x),
    cols = columns(a);
  return (
    <section className="equation-card" aria-label="Column combination">
      <div>
        <h3>Linear combination of columns</h3>
      </div>
      <MathText
        block
        tex={`${symbol}${input}=${x.map((_, j) => `${input}_{${j + 1}}${col}_{${j + 1}}`).join("+")}=${texVector(y)}`}
      />
      <div className="column-terms">
        {cols.map((c, j) => (
          <div key={j} style={{ borderTopColor: COLORS[j] }}>
            <MathText
              tex={`${symbol}e_{${j + 1}}=${col}_{${j + 1}}=${texVector(c)}`}
            />
            <MathText
              tex={`${x[j].tex()}\\,${col}_{${j + 1}}=${texVector(c.map((v) => v.mul(x[j])))}`}
            />
          </div>
        ))}
      </div>
    </section>
  );
}
function TransposeReadout({ a }: { a: Matrix }) {
  const [cell, setCell] = useState<[number, number]>([0, 0]);
  return (
    <section className="derived-card">
      <h3>Transpose entries</h3>
      <p>
        Select an entry to trace its position:{" "}
        <MathText tex={"(A^{\\mathsf T})_{ji}=A_{ij}"} />.
      </p>
      <div className="transpose-pair">
        {[a, transpose(a)].map((m, index) => (
          <div key={index}>
            <b>{index === 0 ? "A" : "Aᵀ"}</b>
            <div
              className="readout-matrix"
              style={{ gridTemplateColumns: `repeat(${m[0].length}, 1fr)` }}
            >
              {m.flatMap((r, i) =>
                r.map((q, j) => (
                  <button
                    key={`${i}-${j}`}
                    className={
                      cell[0] === (index ? j : i) && cell[1] === (index ? i : j)
                        ? "highlighted"
                        : ""
                    }
                    onClick={() => setCell(index ? [j, i] : [i, j])}
                    aria-label={`${index ? "transpose" : "original"} entry row ${i + 1} column ${j + 1}`}
                    aria-pressed={
                      cell[0] === (index ? j : i) && cell[1] === (index ? i : j)
                    }
                  >
                    {q.toString()}
                  </button>
                )),
              )}
            </div>
          </div>
        ))}
      </div>
      <p>
        Transposition swaps input and output dimensions. It generally does not
        undo A.
      </p>
    </section>
  );
}
function Matrices({ s, dispatch }: { s: State; dispatch: Dispatch }) {
  const a = fromNumbers(s.a),
    m = a.length,
    n = a[0].length;
  const operation = operationView(a, s.operation);
  const {
    matrix: shown,
    symbol,
    label,
    input,
    column,
    unavailable,
  } = operation;
  const isTranspose = s.operation === "transpose",
    isInverse = s.operation === "inverse";
  const inputValues = isTranspose ? s.transposeX : isInverse ? s.inverseY : s.x;
  const x = vector(inputValues),
    y = shown ? multiplyVector(shown, x) : null;
  const patch = (value: Partial<State>) => dispatch({ type: "patch", value });
  const updateInput = (v: number[]) =>
    patch(
      isTranspose ? { transposeX: v } : isInverse ? { inverseY: v } : { x: v },
    );
  const updateColumn = (j: number, v: number[]) =>
    patch({
      a: s.a.map((row, i) => row.map((value, k) => (k === j ? v[i] : value))),
    });
  return (
    <div className="workspace">
      <aside className="controls panel">
        <h2>Source matrix A</h2>
        <Dimensions
          m={m}
          n={n}
          onChange={(m, n) => dispatch({ type: "shape", m, n })}
        />
        <label className="select-label">
          Named example
          <select
            aria-label="Named matrix example"
            value={selectedPreset(presets(m, n), s.a)}
            onChange={(e) => {
              const choice = presets(m, n).find((p) => p.id === e.target.value);
              if (choice) patch({ a: choice.values });
            }}
          >
            <option value="custom" disabled>
              Custom matrix
            </option>
            {presets(m, n).map((p) => (
              <option value={p.id} key={p.id}>
                {p.label}
              </option>
            ))}
          </select>
        </label>
        <div className="editor-heading">
          <b>A</b>
          <MathText
            tex={`\\mathbb R^{${n}}\\longrightarrow\\mathbb R^{${m}}`}
          />
        </div>
        <MatrixEditor values={s.a} name="A" onChange={(a) => patch({ a })} />
        <p className="input-hint">
          Edit from −3 to 3 in steps of 0.5. Enter or leave a field to apply.
          Arrow keys change by 0.5.
        </p>
        <div className="operation-buttons">
          <button
            aria-pressed={isInverse}
            onClick={() =>
              patch({ operation: isInverse ? "original" : "inverse" })
            }
          >
            {isInverse ? "Hide inverse" : "Show inverse"}
          </button>
          <button
            aria-pressed={isTranspose}
            onClick={() =>
              patch({ operation: isTranspose ? "original" : "transpose" })
            }
          >
            {isTranspose ? "Hide transpose" : "Show transpose"}
          </button>
        </div>
        {(isInverse || isTranspose) && (
          <p className="input-hint">
            The plots show {label}, calculated from this source matrix. Each
            operation retains its own input vector.
          </p>
        )}
        {shown && (
          <>
            <div className="control-divider" />
            <h3>
              Input {input} for {label}
            </h3>
            <VectorEditor
              name={input}
              values={inputValues}
              onChange={updateInput}
            />
          </>
        )}
      </aside>
      <div className="visual-area" data-operation={s.operation}>
        <section className="operator-summary" aria-label="Displayed operation">
          <div className="map-heading">
            <h2>
              {isInverse
                ? "Inverse transformation"
                : isTranspose
                  ? "Transpose transformation"
                  : "Matrix transformation"}
            </h2>
            {shown && (
              <MathText
                tex={`${symbol}:\\mathbb R^{${shown[0].length}}\\longrightarrow\\mathbb R^{${shown.length}}`}
              />
            )}
          </div>
          {shown ? (
            <>
              <div className="operator-values">
                <MathText block tex={`${symbol}=${texMatrix(shown)}`} />
                <Stats matrix={shown} symbol={label} />
              </div>
              {isInverse && (
                <p>
                  The plots apply A⁻¹ to y. Applying A to the result recovers y.
                </p>
              )}
              {isTranspose && (
                <p>
                  The plots apply Aᵀ to u. Transposing exchanges rows and
                  columns; it generally does not undo A.
                </p>
              )}
            </>
          ) : (
            <p className="notice" role="status">
              {unavailable}
            </p>
          )}
        </section>
        {shown && y && (
          <>
            <div className="spaces">
              <Space
                key={`in-${shown[0].length}-${s.resetKey}`}
                title="Input space"
                dimension={shown[0].length}
                arrows={[
                  {
                    id: "input",
                    label: input,
                    value: x,
                    color: DARK,
                    onChange: updateInput,
                  },
                ]}
                unit={identity(shown[0].length)}
                unitLabel={`unit ${["", "interval", "square", "cube"][shown[0].length]}`}
              />
              <Space
                key={`out-${shown.length}-${s.resetKey}`}
                title="Output space"
                dimension={shown.length}
                arrows={[
                  ...columnArrows(
                    shown,
                    column,
                    s.operation === "original" ? updateColumn : undefined,
                  ),
                  {
                    id: "output",
                    label: `${label}${input}`,
                    value: y,
                    color: DARK,
                  },
                ]}
                span={shown}
                unit={shown}
                unitLabel={`image of the unit ${["", "interval", "square", "cube"][shown[0].length]} under ${label}`}
                description={
                  s.operation === "original"
                    ? "Drag a column endpoint to change A."
                    : `Columns of ${label} are calculated from A.`
                }
              />
            </div>
            <Combination
              a={shown}
              x={x}
              symbol={symbol}
              input={input}
              col={column}
            />
            {isInverse && (
              <section
                className="derived-card inverse-check"
                aria-label="Inverse check"
              >
                <h3>Inverse identity</h3>
                <MathText
                  block
                  tex={`A(A^{-1}y)=A${texVector(y)}=${texVector(multiplyVector(a, y))}=y`}
                />
                <p data-testid="inverse-recovered">
                  Recovered y = {coordinates(multiplyVector(a, y))}
                </p>
              </section>
            )}
            {isTranspose && (
              <details className="transpose-details">
                <summary>Entry correspondence</summary>
                <TransposeReadout a={a} />
              </details>
            )}
          </>
        )}
      </div>
    </div>
  );
}
function Bases({ s, dispatch }: { s: State; dispatch: Dispatch }) {
  const b = fromNumbers(s.b),
    v = vector(s.v),
    c = basisCoordinates(b, v),
    d = b.length;
  const patch = (value: Partial<State>) => dispatch({ type: "patch", value });
  return (
    <div className="workspace">
      <aside className="controls panel">
        <h2>Basis vectors</h2>
        <label className="select-label">
          Dimension
          <select
            aria-label="Basis dimension"
            value={d}
            onChange={(e) =>
              dispatch({ type: "basisDimension", d: Number(e.target.value) })
            }
          >
            {[1, 2, 3].map((i) => (
              <option key={i}>{i}</option>
            ))}
          </select>
        </label>
        <label className="select-label">
          Named example
          <select
            aria-label="Named basis example"
            value={selectedPreset(basisPresets(d), s.b)}
            onChange={(e) => {
              const preset = basisPresets(d).find(
                (p) => p.id === e.target.value,
              );
              if (preset) patch({ b: preset.values });
            }}
          >
            <option value="custom" disabled>
              Custom vectors
            </option>
            {basisPresets(d).map((p) => (
              <option key={p.id} value={p.id}>
                {p.label}
              </option>
            ))}
          </select>
        </label>
        <div className="editor-heading">
          <b>B = [b₁ … b{d}]</b>
        </div>
        <MatrixEditor values={s.b} name="B" onChange={(b) => patch({ b })} />
        <p className="input-hint">
          Basis vectors are columns. Editing B holds v fixed in standard
          coordinates.
        </p>
        <h3>Vector v · standard coordinates</h3>
        <VectorEditor name="v" values={s.v} onChange={(v) => patch({ v })} />
        <Stats matrix={b} symbol="B" />
        <div
          className={c ? "basis-status" : "basis-status notice"}
          aria-live="polite"
        >
          <strong>{c ? "A basis" : "Not a basis"}</strong>
          <p>
            {c
              ? `Coordinates in B: ${coordinates(c)}`
              : "The columns are dependent. Unique basis coordinates are unavailable."}
          </p>
        </div>
      </aside>
      <div className="visual-area">
        <div className="map-heading">
          <MathText tex={`v=B[v]_B`} />
          <span>Basis coordinates</span>
        </div>
        <div className="spaces">
          <Space
            key={`basis-${d}-${s.resetKey}`}
            title="Geometric space"
            dimension={d}
            span={b}
            gridBasis={c ? b : undefined}
            arrows={[
              ...columnArrows(b, "b", (j, value) =>
                patch({
                  b: s.b.map((r, i) =>
                    r.map((x, k) => (j === k ? value[i] : x)),
                  ),
                }),
              ),
              {
                id: "target",
                label: "v",
                value: v,
                color: DARK,
                onChange: (v) => patch({ v }),
              },
            ]}
            description="Dashed lines follow the chosen basis directions. Solid gray axes use standard coordinates."
          />
          {c ? (
            <Space
              key={`coord-${d}-${s.resetKey}`}
              title="Basis coordinate space"
              dimension={d}
              axisLabels={["c₁", "c₂", "c₃"]}
              arrows={[
                { id: "coordinates", label: "[v]B", value: c, color: GREEN },
              ]}
              description="Read-only coefficients c = B⁻¹v. Edit B or v in the left panel to change them; calculated values retain exact fractions."
            />
          ) : (
            <section className="empty-space">
              <span>Dependent columns</span>
              <h3>No unique coordinate system</h3>
              <p>Move the basis vectors to make them linearly independent.</p>
            </section>
          )}
        </div>
        {c && (
          <section className="equation-card">
            <h3>Vector reconstruction</h3>
            <MathText
              block
              tex={`${texVector(v)}=${texMatrix(b)}${texVector(c)}=${c.map((q, j) => `\\left(${q.tex()}\\right)b_{${j + 1}}`).join("+")}`}
            />
          </section>
        )}
      </div>
    </div>
  );
}
function OLS({ s, dispatch }: { s: State; dispatch: Dispatch }) {
  const y = vector(s.y),
    fit = ols(y);
  return (
    <section className="ols-panel" aria-label="OLS example">
      <div className="section-heading">
        <div>
          <h2>Ordinary least squares</h2>
        </div>
        <span className="tag">3 observations · 2 coefficients</span>
      </div>
      <div className="ols-layout">
        <div className="ols-copy">
          <p>
            A fixed design matrix has an intercept and predictor values −1, 0,
            1. Change y to see its projection onto the column plane.
          </p>
          <MathText block tex={`X=${texMatrix(OLS_X)}`} />
          <VectorEditor
            values={s.y}
            name="y"
            onChange={(y) => dispatch({ type: "patch", value: { y } })}
          />
          <MathText
            block
            tex={`\\hat\\beta=(X^{\\mathsf T}X)^{-1}X^{\\mathsf T}y=${texVector(fit.beta)}`}
          />
          <p data-testid="ols-fitted">Fitted ŷ = {coordinates(fit.fitted)}</p>
          <p data-testid="ols-residual">
            Residual r = {coordinates(fit.residual)}
          </p>
          <MathText
            tex={`X^{\\mathsf T}(y-\\hat y)=${texVector(multiplyVector(transpose(OLS_X), fit.residual))}`}
          />
          <p>
            The residual segment starts at ŷ and ends at y. It is perpendicular
            to the column plane.
          </p>
        </div>
        <Space
          key={s.resetKey}
          title="Observation space"
          dimension={3}
          span={OLS_X}
          arrows={[
            ...columnArrows(OLS_X, "X"),
            {
              id: "response",
              label: "y",
              value: y,
              color: DARK,
              onChange: (y) => dispatch({ type: "patch", value: { y } }),
            },
            { id: "fitted", label: "ŷ", value: fit.fitted, color: GREEN },
            {
              id: "residual",
              label: "r = y − ŷ",
              start: fit.fitted,
              value: fit.residual,
              color: "#905b1d",
              dashed: true,
            },
          ]}
        />
      </div>
    </section>
  );
}
export default function App() {
  const [s, dispatch] = useReducer(reducer, undefined, initialState);
  const switchTab = (tab: State["tab"]) =>
    dispatch({ type: "patch", value: { tab } });
  return (
    <div className="lab">
      <header className="lab-header">
        <div>
          <h1>Linear Algebra Lab</h1>
        </div>
        <a
          className="repo-link"
          href="https://github.com/m-laprise/linear-algebra-lab"
          target="_blank"
          rel="noreferrer"
        >
          View source on GitHub ↗
        </a>
      </header>
      <div className="top-controls">
        <div
          className="tabs"
          role="tablist"
          aria-label="Dashboard views"
          onKeyDown={(e) => {
            if (["ArrowLeft", "ArrowRight", "Home", "End"].includes(e.key)) {
              e.preventDefault();
              const tab =
                e.key === "Home"
                  ? "matrices"
                  : e.key === "End"
                    ? "bases"
                    : s.tab === "matrices"
                      ? "bases"
                      : "matrices";
              switchTab(tab);
              document.getElementById(`${tab}-tab`)?.focus();
            }
          }}
        >
          <button
            role="tab"
            id="matrices-tab"
            tabIndex={s.tab === "matrices" ? 0 : -1}
            aria-selected={s.tab === "matrices"}
            aria-controls={s.tab === "matrices" ? "matrices-panel" : undefined}
            onClick={() => switchTab("matrices")}
          >
            Matrices
          </button>
          <button
            role="tab"
            id="bases-tab"
            tabIndex={s.tab === "bases" ? 0 : -1}
            aria-selected={s.tab === "bases"}
            aria-controls={s.tab === "bases" ? "bases-panel" : undefined}
            onClick={() => switchTab("bases")}
          >
            Bases
          </button>
        </div>
        <div className="utility-controls">
          <button className="reset" onClick={() => dispatch({ type: "reset" })}>
            ↺ Reset all
          </button>
        </div>
      </div>
      <main>
        <div
          key={s.resetKey}
          id={`${s.tab}-panel`}
          role="tabpanel"
          aria-labelledby={`${s.tab}-tab`}
        >
          <p className="tab-description">
            {s.tab === "matrices" ? (
              <>
                A matrix maps an input vector to an output vector. Its columns
                are the images of the standard basis vectors, and multiplying by
                the matrix forms a linear combination of those columns. The
                plots show the input and output spaces and the transformation of
                a unit interval, square, or cube.
              </>
            ) : (
              <>
                A basis assigns coordinates to vectors using a set of linearly
                independent vectors. The left plot shows the basis vectors and v
                in standard coordinates; the right plot shows the coefficients
                needed to express v in that basis. Changing the basis holds v
                fixed and changes its coefficients.
              </>
            )}
          </p>
          {s.tab === "matrices" ? (
            <Matrices s={s} dispatch={dispatch} />
          ) : (
            <Bases s={s} dispatch={dispatch} />
          )}
        </div>
        <div className="ols-toggle">
          <label>
            <input
              type="checkbox"
              checked={s.showOLS}
              onChange={(e) =>
                dispatch({
                  type: "patch",
                  value: { showOLS: e.target.checked },
                })
              }
            />{" "}
            Show OLS example
          </label>
        </div>
        {s.showOLS && <OLS s={s} dispatch={dispatch} />}
      </main>
      <footer className="lab-footer">
        <p>
          <strong>About this dashboard</strong>
        </p>
        <p>{CAPTION}</p>
        <a
          href="https://github.com/m-laprise/linear-algebra-lab/tree/main/docs"
          target="_blank"
          rel="noreferrer"
        >
          Project prompts and documentation ↗
        </a>
      </footer>
    </div>
  );
}
